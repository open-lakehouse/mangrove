#!/usr/bin/env bun
/**
 * Copies the built MCP App (dist/index.html) to where `uc mcp serve` embeds it
 * (crates/cli/assets/mcp/grants-app.html, via include_str!), marked generated.
 * The cli crate can't run the node build, and a published crate must carry
 * the file, so the bundle is committed; CI rebuilds it and fails on drift.
 *
 * Run from the package directory (`bun run sync:cli`, after `bun run build`),
 * or `just build mcp-app` from anywhere. `--check` compares instead of writing.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const HEADER =
  "<!-- @generated by node/uc-a2ui (`just build mcp-app`). Do not edit. -->\n";
const built = join(process.cwd(), "dist", "index.html");
const target = join(
  process.cwd(),
  "..",
  "..",
  "crates",
  "cli",
  "assets",
  "mcp",
  "grants-app.html",
);

const want = HEADER + readFileSync(built, "utf8");
if (process.argv.includes("--check")) {
  let have = "";
  try {
    have = readFileSync(target, "utf8");
  } catch {}
  if (have !== want) {
    console.error(
      "crates/cli/assets/mcp/grants-app.html is stale: run `just build mcp-app` and commit it.",
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, want);
  console.log(`→ wrote ${target}`);
}
