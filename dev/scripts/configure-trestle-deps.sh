#!/usr/bin/env bash
# Write .cargo/config.toml patching the trestle crates (olai-http, olai-http-wasm,
# olai-store and the credential vending crates) from the local trestle checkout.
# The directory is gitignored so CI (crates.io) is unaffected. Cargo also reads this
# file when building from the `wasm/` workspace, since it is an ancestor directory.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

if ! command -v trestle >/dev/null 2>&1; then
    echo "error: trestle CLI not found on PATH" >&2
    echo "  Install from https://github.com/open-lakehouse/trestle (Homebrew tap or release binary)." >&2
    exit 1
fi

trestle_root="$("$repo_root/dev/scripts/trestle-root.sh")"
crates="$trestle_root/crates"

mkdir -p "$repo_root/.cargo"
cat >"$repo_root/.cargo/config.toml" <<EOF
# Generated by dev/scripts/configure-trestle-deps.sh — do not commit (.cargo/ is gitignored).
# Patches the trestle crates from the local trestle checkout so builds work when
# crates.io (or a corporate proxy age filter) cannot resolve the published versions.
# CI resolves these crates from crates.io instead.

[patch.crates-io]
olai-credential-vending = { path = "$crates/olai-credential-vending" }
olai-http = { path = "$crates/olai-http" }
olai-http-wasm = { path = "$crates/olai-http-wasm" }
olai-storage-credentials = { path = "$crates/olai-storage-credentials" }
olai-store = { path = "$crates/olai-store" }
olai-vended-store = { path = "$crates/olai-vended-store" }
EOF

echo "Wrote $repo_root/.cargo/config.toml"
echo "  trestle root: $trestle_root"
echo "  trestle CLI:  $(command -v trestle) ($(trestle --version))"
