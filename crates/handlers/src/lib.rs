#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    #[test]
    fn test_wiring_matches_trestle_root() {
        let generated: BTreeSet<String> = include_str!("codegen/mod.rs")
            .lines()
            .filter_map(|line| line.trim().strip_prefix("pub mod "))
            .map(|name| name.trim_end_matches(';').to_string())
            .collect();
        let ours: BTreeSet<String> = include_str!("lib.rs")
            .lines()
            .filter_map(|line| line.trim().strip_prefix("#[path = \"codegen/"))
            .map(|path| path.trim_end_matches("/mod.rs\"]").to_string())
            .collect();
        assert!(!generated.is_empty(), "no services found in codegen/mod.rs");
        assert_eq!(
            generated, ours,
            "lib.rs must mount exactly the services in the trestle-emitted codegen/mod.rs"
        );
    }
}
