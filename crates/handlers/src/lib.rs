//! Unity Catalog handler traits, gated per resource.
//!
//! Each Unity Catalog service gets a generated async handler trait (one method per
//! RPC), e.g. [`catalogs::CatalogHandler`], and, with the `axum` feature, a
//! `server` module of axum route functions that delegate to it. Implement the
//! trait for your backend, then mount the route functions onto an
//! [`axum::Router`] with that implementation as state.
//!
//! The crate also holds the few types the traits depend on: the [`Error`] /
//! [`Result`] the methods return, and the default request context
//! [`RequestContext`] (carrying the caller's [`Principal`]). The traits are generic
//! over the context, so a service can authorize against its own type instead.
//!
//! # Feature flags
//!
//! Every service sits behind the resource feature of the model package it is built
//! on, with the same names as `olai-uc-common` (`catalogs`, `credentials`, …;
//! `tags` covers both the entity-tag-assignment and tag-policy services).
//! `all-resources` (default) enables them all.
//!
//! - `axum` — the route functions, `IntoResponse` for [`Error`] and
//!   `FromRequestParts` for [`RequestContext`].
//! - `object-store`, `store`, `cloud` — [`Error`] variants and `From` impls for
//!   `object_store`, `olai-store` and `olai-http` errors, for backends built on
//!   those crates.
//!
//! The generated code lives under `src/codegen/` (regenerated by
//! `just generate-code`); this file mounts each service behind its feature in place
//! of the trestle-emitted `codegen/mod.rs`, which is kept as the reference the
//! drift test below checks against.

